import { defineEndpoints } from '../../http/endpoint.js';
import { PageQuery } from '../../http/common.schemas.js';
import {
  Classroom,
  ClassroomIdParams,
  ClassroomPage,
  CreateClassroomBody,
  JoinCode,
  RosterPage,
  RosterStudentParams,
  UpdateClassroomBody,
} from './schemas.js';

export const classroomsEndpoints = defineEndpoints({
  listClassrooms: {
    method: 'GET',
    path: '/v1/classrooms',
    tag: 'Classrooms',
    summary: "List the teacher's classrooms",
    description: 'Newest first, cursor paginated.',
    access: 'teacher',
    query: PageQuery,
    responses: { 200: ClassroomPage },
    errors: [],
  },
  createClassroom: {
    method: 'POST',
    path: '/v1/classrooms',
    tag: 'Classrooms',
    summary: 'Create a classroom',
    description:
      'The classroom is created with its first join code. Limited to 30 new classrooms or codes per hour per account.',
    access: 'teacher',
    body: CreateClassroomBody,
    responses: { 201: Classroom },
    errors: ['RATE_LIMITED'],
  },
  getClassroom: {
    method: 'GET',
    path: '/v1/classrooms/:id',
    tag: 'Classrooms',
    summary: 'Get a classroom',
    description: "Another teacher's classroom returns 404, not 403 (does not confirm it exists).",
    access: 'teacher',
    params: ClassroomIdParams,
    responses: { 200: Classroom },
    errors: ['NOT_FOUND'],
  },
  updateClassroom: {
    method: 'PATCH',
    path: '/v1/classrooms/:id',
    tag: 'Classrooms',
    summary: 'Rename, describe, or open/close joining',
    access: 'teacher',
    params: ClassroomIdParams,
    body: UpdateClassroomBody,
    responses: { 200: Classroom },
    errors: ['NOT_FOUND'],
  },
  deleteClassroom: {
    method: 'DELETE',
    path: '/v1/classrooms/:id',
    tag: 'Classrooms',
    summary: 'Delete a classroom',
    description: 'Hard delete, cascading to join codes and enrollments.',
    access: 'teacher',
    params: ClassroomIdParams,
    responses: { 204: null },
    errors: ['NOT_FOUND'],
  },
  getJoinCode: {
    method: 'GET',
    path: '/v1/classrooms/:id/join-code',
    tag: 'Classrooms',
    summary: 'Get the live join code',
    description: 'Returns 404 NOT_FOUND if there is no live code (the last one expired).',
    access: 'teacher',
    params: ClassroomIdParams,
    responses: { 200: JoinCode },
    errors: ['NOT_FOUND'],
  },
  regenerateJoinCode: {
    method: 'POST',
    path: '/v1/classrooms/:id/join-code',
    tag: 'Classrooms',
    summary: 'Regenerate the join code',
    description:
      'Revokes the current code (and its QR) immediately and issues a new one. Shares the 30 per hour limit with creating classrooms.',
    access: 'teacher',
    params: ClassroomIdParams,
    responses: { 201: JoinCode },
    errors: ['NOT_FOUND', 'RATE_LIMITED'],
  },
  listStudents: {
    method: 'GET',
    path: '/v1/classrooms/:id/students',
    tag: 'Classrooms',
    summary: 'List the roster',
    description: 'Most recent joins first. Polled by the invite screen for the live roster.',
    access: 'teacher',
    params: ClassroomIdParams,
    query: PageQuery,
    responses: { 200: RosterPage },
    errors: ['NOT_FOUND'],
  },
  removeStudent: {
    method: 'DELETE',
    path: '/v1/classrooms/:id/students/:studentId',
    tag: 'Classrooms',
    summary: 'Remove a student',
    access: 'teacher',
    params: RosterStudentParams,
    responses: { 204: null },
    errors: ['NOT_FOUND'],
  },
});
